/**
 * split-framer-css.mjs — one-time bootstrap that carves the home's combined
 * `src/app/framer.css` into:
 *   - src/app/framer-global.css : shared rules (55 @font-face, reset, tokens,
 *     presets, breakpoint media queries, every "chrome" component scoped under
 *     its own hash — header/footer/floating/etc. — and the POC override block).
 *   - src/app/framer-home.css   : home-only rules (everything scoped under the
 *     page-root hash `.framer-pK5Ni`).
 *
 * The split is lossless: framer-global + framer-home == framer.css rule-for-rule
 * (content-addressed hashes never collide, so load order global-then-page keeps
 * the home byte-identical). Run once; thereafter the two files are the sources
 * of truth and framer.css can be removed.
 *
 * Usage: node scripts/split-framer-css.mjs [--check]
 *   --check  : report the split sizes without writing.
 */

import fs from "node:fs";
import path from "node:path";
import { splitCssByRootHash } from "./lib/css-split.mjs";

const HOME_ROOT_HASH = "pK5Ni";
const appDir = path.join(process.cwd(), "src", "app");
const srcPath = path.join(appDir, "framer.css");

const css = fs.readFileSync(srcPath, "utf8");
const { global, page } = splitCssByRootHash(css, HOME_ROOT_HASH);

console.log(`[split] source  : ${css.length} bytes`);
console.log(`[split] global  : ${global.length} bytes  (@font-face x${global.split("@font-face").length - 1})`);
console.log(`[split] home    : ${page.length} bytes  (.framer-${HOME_ROOT_HASH} x${page.split(`.framer-${HOME_ROOT_HASH}`).length - 1})`);
console.log(`[split] home-hash leaked into global: ${global.split(`.framer-${HOME_ROOT_HASH}`).length - 1} (must be 0)`);

if (process.argv.includes("--check")) {
  console.log("[split] --check: nothing written.");
  process.exit(0);
}

const globalHeader =
  "/* framer-global.css — shared Framer CSS for ALL pages.\n" +
  "   Imported once in layout.tsx (after globals.css). Generated by\n" +
  "   scripts/split-framer-css.mjs from the home's framer.css.\n" +
  "   Contains: @font-face, reset/tokens/presets, breakpoint media queries,\n" +
  "   shared chrome components, and the POC static-port override block. */\n";
const homeHeader =
  "/* framer-home.css — home-only Framer CSS (rules scoped under .framer-pK5Ni).\n" +
  "   Imported by src/app/page.tsx, after framer-global.css. */\n";

fs.writeFileSync(path.join(appDir, "framer-global.css"), globalHeader + global);
fs.writeFileSync(path.join(appDir, "framer-home.css"), homeHeader + page);
console.log("[split] wrote framer-global.css + framer-home.css");
